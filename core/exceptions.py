class BotException(Exception):
    """الاستثناء الأساسي الذي ترث منه كل استثناءات البوت."""

    def __init__(self, message: str = "حدث خطأ غير متوقع"):
        self.message = message
        super().__init__(self.message)


# ═══════════════════════════════════════════════════════════════
# استثناءات قاعدة البيانات
# ═══════════════════════════════════════════════════════════════
class DatabaseException(BotException):
    """خطأ في قاعدة البيانات."""
    pass


class DatabaseConnectionError(DatabaseException):
    """فشل الاتصال بقاعدة البيانات."""
    pass


# ═══════════════════════════════════════════════════════════════
# استثناءات Redis
# ═══════════════════════════════════════════════════════════════
class RedisException(BotException):
    """خطأ في Redis."""
    pass


# ═══════════════════════════════════════════════════════════════
# استثناءات الصلاحيات
# ═══════════════════════════════════════════════════════════════
class PermissionDenied(BotException):
    """المستخدم لا يملك الصلاحية المطلوبة."""

    def __init__(self, message: str = "ليس لديك صلاحية لتنفيذ هذا الأمر"):
        super().__init__(message)


class InsufficientRank(PermissionDenied):
    """رتبة المستخدم أقل من المطلوب."""

    def __init__(self, message: str = "رتبتك لا تسمح بهذا الإجراء"):
        super().__init__(message)


class CannotModifyHigherRank(PermissionDenied):
    """محاولة تعديل رتبة أعلى أو مساوية."""

    def __init__(self, message: str = "لا يمكنك تعديل رتبة أعلى من رتبتك أو مساوية لها"):
        super().__init__(message)


# ═══════════════════════════════════════════════════════════════
# استثناءات التحقق من المدخلات
# ═══════════════════════════════════════════════════════════════
class ValidationError(BotException):
    """خطأ في التحقق من صحة المدخلات."""
    pass


# ═══════════════════════════════════════════════════════════════
# استثناءات معدل الاستخدام
# ═══════════════════════════════════════════════════════════════
class RateLimitExceeded(BotException):
    """تجاوز المستخدم الحد المسموح من الطلبات."""

    def __init__(self, message: str = "لقد تجاوزت الحد المسموح، حاول لاحقاً"):
        super().__init__(message)


# ═══════════════════════════════════════════════════════════════
# استثناءات وضع الصيانة
# ═══════════════════════════════════════════════════════════════
class MaintenanceMode(BotException):
    """البوت في وضع الصيانة."""

    def __init__(self, message: str = "البوت في وضع الصيانة حالياً، يرجى المحاولة لاحقاً"):
        super().__init__(message)


# ═══════════════════════════════════════════════════════════════
# استثناءات الكيانات غير الموجودة
# ═══════════════════════════════════════════════════════════════
class EntityNotFound(BotException):
    """الكيان المطلوب (مستخدم/مجموعة) غير موجود."""
    pass


class UserNotFound(EntityNotFound):
    def __init__(self, message: str = "المستخدم غير موجود"):
        super().__init__(message)


class GroupNotFound(EntityNotFound):
    def __init__(self, message: str = "المجموعة غير موجودة"):
        super().__init__(message)
